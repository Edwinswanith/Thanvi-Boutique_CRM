"use client";

import { toSVG } from "bwip-js/browser";
import { useMemo } from "react";
import { isCode39Safe } from "@/lib/code39";

interface BarcodeProps {
  value: string;
  height?: number;
  className?: string;
}

/** Renders a Code 39 barcode as inline SVG. Input is validated against the Code 39 charset first. */
export function Barcode({ value, height = 12, className }: BarcodeProps) {
  const svg = useMemo(() => {
    if (!value || !isCode39Safe(value)) return null;
    try {
      return toSVG({ bcid: "code39", text: value, height, includetext: true, textxalign: "center", textsize: 9, scale: 2 });
    } catch {
      return null;
    }
  }, [value, height]);

  if (!svg) {
    return <div className={`flex items-center justify-center text-xs text-madder ${className ?? ""}`}>Not a valid Code 39 value</div>;
  }
  // svg is generated by bwip-js from a Code 39–validated string, never from raw user HTML.
  return <div className={className} aria-label={`Barcode ${value}`} role="img" dangerouslySetInnerHTML={{ __html: svg }} />;
}
